# 一.提示词(prompt)
# 引导大模型(LLM)进行内容生成的命令
# 例如:用python写一个游戏---这不是一个好的提示词
# 引导AI思考,约束其输出范围,明确你的期望成果
# 二.提示词工程
# 通过有技巧的编写提示词,使大模型生成尽可能符合预期的内容,这一过程称为提示词工程
# 1.给大模型设定角色与能力:你是一名经验丰富的高中历史老师,擅长生动有趣的讲解复杂的历史事件
# 2.明确核心请求与任务:例如请向一位高中生解释法国大革命爆发的主要原因
# 3.按步骤拆解复杂任务:请先概述背景,然后分政治,经济,思想三个方面概述,每点举一个例子
# 4.指定风格和语气:请用简洁,口语化,充满热情的语气(避免使用过度学术的术语)
# 5.明确要求的输出格式:请严格按照如下格式输出
# 6.提供输入输出的示例:可以参考<<人类群星闪耀>>的叙事风格,请不要列出冗长的日期列表

# 总的来说就是   角色-->任务-->要求
# 给大模型设定角色与能力     明确核心请求与任务  按步骤拆解复杂任务     指定风格与语气 明确要求输出格式 提供输入输出的示例

# 三.例子
# 你是一名经验丰富的历史老师，擅长用生动有趣的方式讲述复杂的历史事件。现在，请完成以下任务：
# 1.核心任务：向一位高中生解释法国大革命爆发的主要原因。
# 2.表达要求：
#     语气与风格：使用简洁、口语化、充满课堂热情的语气，避免学术黑话。整体叙事可以借鉴《人类群星闪耀时》中对历史关键时刻的描写手法，富有画面感和戏剧性。
#     内容禁忌：聚焦于原因分析，不要罗列冗长的日期和事件过程表。
# 3.内容与结构要求：
#     开头：先用一段话，生动描述革命前法国社会的总体氛围和紧张感（即背景概述）。
#     主体：分别从政治、经济、思想三个层面阐述直接原因。每个层面提炼 2 个关键点，并为每个关键点配 1 个具体、有说服力的史实例子。
#     结尾：提供一个帮助学生记忆的妙招。
# 4.输出格式：请严格、完整地按照以下框架组织你的回答：
#     【历史现场氛围】
#     （在这里写你的背景概述）
#     【危机根源解析】
#     政治层面：
#     关键点 1：… 例子：…
#     关键点 2：… 例子：…
#     经济层面：
#     关键点 1：… 例子：…
#     关键点 2：… 例子：…
#     思想层面：
#     关键点 1：… 例子：…
#     关键点 2：… 例子：…
#     【记忆法宝】
#     （请提供一个巧妙的比喻、口诀或联想图像，将这三大层面串联起来，方便学生瞬间记忆）