# 四.函数的嵌套调用
# 1.函数的嵌套调用:在一个函数中调用另一个函数
# 2.函数调用遵循栈结构,最后被调用的函数最先返回LFUO(Last In First Out,后进先出)
# 3.函数的嵌套调用与函数的定义顺序无关,只要函数名存在就可以调用
# 4.栈:就相当于弹夹最后压进去的子弹最先射出去,所以运行嵌套函数时,先运行最里层的函数

