# 2．定义一个函数：计算传入的字符串中元音字母的个数（元音字母为 aeiouAEIOU）。
# -------------------------------代码演示-------------------------------------------
def count_vowels(s):
    """
    计算字符串中元音字母的个数
    :param s: 字符串
    :return: 元音字母的个数
    """
    count = 0
    for i in s:
        if i in "aeiouAEIOU":
            count += 1
    return count
# 调用函数
print(count_vowels("hello world"))
# 3．定义一个函数：计算传入的班级学员高考成绩列表中成绩的最高分、最低分、平均分 (保留 1 位小数) 并返回。
def calc_score(socre_list):
    """
    计算成绩列表中的最高分,最低分,平均分
    :param socre_list: 成绩列表
    :return: 最高分,最低分,平均分
    """
    max_s = max(socre_list)
    min_s = min(socre_list)
    # sum求和,round保留一位小数(括号后面的1)  ,len函数作用获取容器中元素的总个数（长度）
    avg_s = round(sum(socre_list) / len(socre_list),1)
    return max_s,min_s,avg_s
# 调用函数
s_list = [100, 90, 80, 70, 60, 50, 40, 30, 20, 10]
max_score,min_Score,avg_score = calc_score(s_list)   #解包操作将三个值分别赋值
print("最高分:",max_score)
print("最低分:",min_Score)
print("平均分:",avg_score)