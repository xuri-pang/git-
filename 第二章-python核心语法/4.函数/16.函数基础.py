# 1．定义一个函数：根据传入的底和高计算三角形面积的函数（三角形面积 = 底 * 高 / 2）。
# -------------------------------代码演示-------------------------------------------
def triangle_area(b,h):
    """
    计算三角形的面积
    :param b: 三角形的底
    :param h: 三角形的高
    :return: 三角形的面积
    """
    return b * h / 2
# 调用函数
print(triangle_area(10,20))
